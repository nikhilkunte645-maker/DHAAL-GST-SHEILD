export interface DhaalState {
  step: number; // 1 to 6
  maxStep: number; // 1 to 6
  language: Language; // 'en' | 'hi' | 'mr'
  isDemoMode: boolean; // Defaults to false (Live API Mode targeting http://localhost:8001)
  apiOnline: boolean; // Live API health status
  
  upload: {
    status: 'idle' | 'parsing' | 'success' | 'error';
    progress: number;
    fileName: string;
    errorType: 'none' | 'unreadable' | 'unsupported';
  };

  uploadedNotice: NoticeMetadata | null;

  confirmedAmount: number | null;
  pauseResolved: boolean;
  daysLeftOverride: number;

  checklist: ChecklistItem[];

  verifierMode: 'pass' | 'fail';
  isRawScanModalOpen: boolean;

  // Actions
  setStep: (step: number) => void;
  setLanguage: (lang: Language) => void;
  setIsDemoMode: (isDemo: boolean) => void;
  setApiOnline: (online: boolean) => void;
  setUploadedNotice: (notice: NoticeMetadata | null) => void;
  startUpload: (fileName?: string) => void;
  setUploadProgress: (progress: number) => void;
  setUploadError: (errorType: 'none' | 'unreadable' | 'unsupported') => void;
  confirmAmount: (amount: number) => void;
  setDaysLeftOverride: (days: number) => void;
  markChecklistUploaded: (id: string) => void;
  setVerifierMode: (mode: 'pass' | 'fail') => void;
  setRawScanModalOpen: (open: boolean) => void;
  resetDemo: () => void;
}

const STORAGE_KEY = 'dhaal_demo_state_v1';

function loadPersistedState(): Partial<DhaalState> | null {
  try {
    if (typeof window !== 'undefined' && window.sessionStorage) {
      const saved = window.sessionStorage.getItem(STORAGE_KEY);
      if (saved) {
        return JSON.parse(saved);
      }
    }
  } catch (e) {
    console.warn('Unable to load demo state from sessionStorage:', e);
  }
  return null;
}

function saveState(state: Partial<DhaalState>) {
  try {
    if (typeof window !== 'undefined' && window.sessionStorage) {
      const toSave = {
        step: state.step,
        maxStep: state.maxStep,
        language: state.language,
        isDemoMode: state.isDemoMode,
        confirmedAmount: state.confirmedAmount,
        pauseResolved: state.pauseResolved,
        daysLeftOverride: state.daysLeftOverride,
        verifierMode: state.verifierMode,
      };
      window.sessionStorage.setItem(STORAGE_KEY, JSON.stringify(toSave));
    }
  } catch (e) {
    console.warn('Unable to save demo state to sessionStorage:', e);
  }
}

const saved = loadPersistedState();

export const useDhaalStore = create<DhaalState>((set, get) => ({
  step: saved?.step || 1,
  maxStep: saved?.maxStep || 1,
  language: saved?.language || 'en',
  isDemoMode: saved?.isDemoMode ?? false, // Defaults to false (Live API Mode)
  apiOnline: true,

  upload: {
    status: 'idle',
    progress: 0,
    fileName: 'FORM_GST_ASMT-10.pdf',
    errorType: 'none',
  },

  uploadedNotice: null,

  confirmedAmount: saved?.confirmedAmount ?? null,
  pauseResolved: saved?.pauseResolved ?? false,
  daysLeftOverride: saved?.daysLeftOverride ?? CANONICAL_DEMO_CASE.daysRemaining, // 12

  checklist: INITIAL_CHECKLIST,

  verifierMode: saved?.verifierMode || 'pass',
  isRawScanModalOpen: false,

  setStep: (step: number) => {
    const { maxStep } = get();
    if (step >= 0 && step <= 6) {
      const nextMax = Math.max(maxStep, step === 0 ? 1 : step);
      set({ step, maxStep: nextMax });
      saveState({ ...get(), step, maxStep: nextMax });
      // Update hash in URL
      if (step === 0) {
        if (window.location.hash !== '#dashboard') {
          window.location.hash = '#dashboard';
        }
      } else {
        const stepHashes = ['#upload', '#confirm', '#explain', '#evidence', '#draft', '#brief'];
        if (window.location.hash !== stepHashes[step - 1]) {
          window.location.hash = stepHashes[step - 1];
        }
      }
    }
  },

  setLanguage: (language: Language) => {
    set({ language });
    saveState({ ...get(), language });
  },

  setIsDemoMode: (isDemoMode: boolean) => {
    set({ isDemoMode });
    saveState({ ...get(), isDemoMode });
  },

  setApiOnline: (apiOnline: boolean) => {
    set({ apiOnline });
  },

  setUploadedNotice: (uploadedNotice: NoticeMetadata | null) => {
    set({ uploadedNotice });
  },

  startUpload: (fileName = 'FORM_GST_ASMT-10.pdf') => {
    set({
      upload: {
        status: 'parsing',
        progress: 15,
        fileName,
        errorType: 'none',
      },
    });
  },

  setUploadProgress: (progress: number) => {
    set((state) => {
      const isDone = progress >= 100;
      const nextMax = Math.max(state.maxStep, isDone ? 2 : state.maxStep);
      return {
        upload: {
          ...state.upload,
          progress,
          status: isDone ? 'success' : 'parsing',
        },
        maxStep: nextMax,
      };
    });
  },

  setUploadError: (errorType: 'none' | 'unreadable' | 'unsupported') => {
    set((state) => ({
      upload: {
        ...state.upload,
        status: errorType === 'none' ? 'idle' : 'error',
        errorType,
      },
    }));
  },

  confirmAmount: (amount: number) => {
    set((state) => {
      const nextMax = Math.max(state.maxStep, 3);
      const updated = {
        confirmedAmount: amount,
        pauseResolved: true,
        maxStep: nextMax,
      };
      saveState({ ...state, ...updated });
      return updated;
    });
  },

  setDaysLeftOverride: (days: number) => {
    set({ daysLeftOverride: days });
    saveState({ ...get(), daysLeftOverride: days });
  },

  markChecklistUploaded: (id: string) => {
    set((state) => {
      const nextChecklist = state.checklist.map((item) => {
        if (item.id === id) {
          return {
            ...item,
            statusBadge: 'Uploaded (User Verified)',
            statusType: 'verified' as const,
            isUploadedByUser: true,
          };
        }
        return item;
      });
      return { checklist: nextChecklist };
    });
  },

  setVerifierMode: (mode: 'pass' | 'fail') => {
    set({ verifierMode: mode });
    saveState({ ...get(), verifierMode: mode });
  },

  setRawScanModalOpen: (open: boolean) => {
    set({ isRawScanModalOpen: open });
  },

  resetDemo: () => {
    try {
      if (typeof window !== 'undefined' && window.sessionStorage) {
        window.sessionStorage.removeItem(STORAGE_KEY);
      }
    } catch {}
    set({
      step: 1,
      maxStep: 1,
      language: 'en',
      isDemoMode: false,
      apiOnline: true,
      uploadedNotice: null,
      upload: {
        status: 'idle',
        progress: 0,
        fileName: 'FORM_GST_ASMT-10.pdf',
        errorType: 'none',
      },
      confirmedAmount: null,
      pauseResolved: false,
      daysLeftOverride: CANONICAL_DEMO_CASE.daysRemaining,
      checklist: INITIAL_CHECKLIST,
      verifierMode: 'pass',
      isRawScanModalOpen: false,
    });
    window.location.hash = '#upload';
  },
}));

if (typeof window !== 'undefined') {
  (window as any).__DHAAL_STORE__ = useDhaalStore;
}
